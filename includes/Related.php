<?php
namespace UAMS_Search;

/** Provider names shown by the four Find-a-Doc page templates. No recursive relationships. */
final class Related {
    public const VERSION = 1;
    public const FIELDS = [
        'location' => 'physician_locations',
        'expertise' => 'physician_expertise',
        'condition' => 'condition_physicians',
        'treatment' => 'treatment_procedure_physicians',
    ];
    public static function ids($value): array {
        $ids = [];
        foreach (is_array($value) ? $value : [$value] as $id) {
            if ((is_int($id) || (is_string($id) && ctype_digit($id))) && (int)$id > 0) { $ids[] = (int)$id; }
        }
        return array_values(array_unique($ids));
    }
    public static function fields(\WP_Post $post): array {
        $field = self::FIELDS[$post->post_type] ?? null;
        if (!$field) { return []; }
        // Raw ACF values also support Find-a-Doc installations using ACF custom tables.
        $value = function_exists('get_field') ? get_field($field, $post->ID, false) : get_post_meta($post->ID, $field, true);
        $fields = []; $weight = (float)Config::get()['related_provider_weight'];
        foreach (self::ids($value) as $id) {
            $provider = get_post($id);
            if ($provider && $provider->post_type !== 'provider') { continue; }
            // Keep dependencies even when a provider is hidden: publishing it must refresh this page.
            $item = ['provider_id' => $id, 'text' => '', 'weight' => $weight, 'source' => 'fields'];
            if ($provider && $provider->post_type === 'provider' && Extractor::eligible($provider)) {
                $item['provider_title'] = $provider->post_title;
                $item['text'] = Text::plain($provider->post_title);
            }
            $fields[] = $item;
        }
        return $fields;
    }
    /** The queue writer holds the lock. INSERT SELECT bounds PHP memory and preserves revisions. */
    public static function queue_dependents(int $site, int $id): void {
        global $wpdb;
        $index = DB::table(); $queue = DB::table('queue');
        // This marker is generated by fields(), including the comma after the numeric ID.
        $marker = '%' . $wpdb->esc_like('"provider_id":' . $id . ',') . '%';
        $types = array_keys(self::FIELDS);
        $marks = implode(',', array_fill(0, count($types), '%s'));
        DB::exec($wpdb->prepare("INSERT INTO `$queue` (site_id,object_id,action,queued_at,available_at)
            SELECT site_id,object_id,'upsert',UTC_TIMESTAMP(),UTC_TIMESTAMP() FROM `$index`
            WHERE site_id=%d AND object_id<>%d AND post_type IN ($marks) AND weighted_data LIKE %s
            ON DUPLICATE KEY UPDATE action='upsert',queued_at=UTC_TIMESTAMP(),available_at=UTC_TIMESTAMP(),attempts=0,revision=revision+1",
            array_merge([$site, $id], $types, [$marker])));
    }
    /** Fail closed while a copied name is stale; the queue then restores the page without that name. */
    public static function public_sql(string $posts, string $meta): string {
        return "NOT EXISTS (SELECT 1 FROM JSON_TABLE(IF(JSON_VALID(i.weighted_data),i.weighted_data,'[]'),'$[*]'
            COLUMNS(provider_id BIGINT PATH '$.provider_id',provider_title LONGTEXT PATH '$.provider_title')) related
            WHERE related.provider_title IS NOT NULL AND NOT EXISTS (
                SELECT 1 FROM `$posts` rp WHERE rp.ID=related.provider_id AND rp.post_type='provider'
                AND rp.post_status='publish' AND rp.post_password='' AND BINARY rp.post_title=BINARY related.provider_title
                AND NOT EXISTS (SELECT 1 FROM `$meta` rm WHERE rm.post_id=rp.ID AND (
                    (rm.meta_key IN ('_uams_search_exclude','physician_hidden') AND rm.meta_value NOT IN ('','0'))
                    OR (rm.meta_key='physician_searchable' AND rm.meta_value='0')))))";
    }
}
