        #[DataProvider('words')]
        public function test_a_word_encodes_to_its_primary_and_alternate_keys(string $word, string $primary, string $alternate): void
        {
            self::assertSame([$primary, $alternate], Phonetic::encode($word));
            self::assertSame($primary, Phonetic::key($word));
        }

        public function test_input_with_no_letters_encodes_to_empty_keys(): void
        {
            self::assertSame(['', ''], Phonetic::encode(''));
            self::assertSame(['', ''], Phonetic::encode('1234 -- !!'));
            self::assertSame('', Phonetic::key('42'));
        }

        public function test_case_and_non_letters_do_not_change_the_encoding(): void
        {
            self::assertSame(Phonetic::encode('Smith'), Phonetic::encode("s-M i.t'h"));
        }
